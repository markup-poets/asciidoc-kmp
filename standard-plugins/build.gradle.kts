import java.util.Base64
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    alias(libs.plugins.kotlinMultiplatform)
    alias(libs.plugins.android.kotlin.multiplatform.library)
    alias(libs.plugins.vanniktech.mavenPublish)
}

group = "org.markup-poet"
version = providers.gradleProperty("VERSION_NAME").get()

// The standard plugins are Kotlin/Wasm modules under plugins/. Their compiled
// binaries are embedded here as generated Kotlin source, so every target gets
// them without platform resource APIs.
val standardPlugins = listOf("icons-fontawesome", "stem-mathjax", "video-embed")
val generatedDir = layout.buildDirectory.dir("generated/standardPlugins/kotlin")

val generatePluginBinaries = tasks.register("generatePluginBinaries") {
    val wasmDirs = standardPlugins.associateWith { name ->
        rootProject.layout.projectDirectory
            .dir("plugins/$name/build/compileSync/wasmWasi/main/productionExecutable/optimized")
    }
    standardPlugins.forEach { dependsOn(":plugin-$it:compileProductionExecutableKotlinWasmWasiOptimize") }
    // The directories are produced by the tasks above; declaring them makes a rebuilt plugin regenerate the source.
    wasmDirs.forEach { (name, dir) -> inputs.dir(dir).withPropertyName("wasm-$name") }
    val output = generatedDir
    outputs.dir(output)
    doLast {
        val encoder = Base64.getEncoder()
        val source = buildString {
            appendLine("// Generated by :standard-plugins:generatePluginBinaries. Do not edit.")
            appendLine("package org.markup.poet.plugin.standard")
            appendLine()
            appendLine("internal object PluginBinaries {")
            wasmDirs.forEach { (name, dir) ->
                val wasm = dir.asFile.listFiles { file -> file.extension == "wasm" }?.singleOrNull()
                    ?: error("expected exactly one .wasm file in ${dir.asFile}")
                // Chunked: a single string constant may not exceed 65535 bytes in a class file.
                val chunks = encoder.encodeToString(wasm.readBytes()).chunked(32_000)
                val property = name.split('-').joinToString("") { it.replaceFirstChar(Char::uppercase) }
                    .replaceFirstChar(Char::lowercase)
                appendLine("    val $property: List<String> = listOf(")
                chunks.forEach { appendLine("        \"$it\",") }
                appendLine("    )")
            }
            appendLine("}")
        }
        val file = output.get().file("org/markup/poet/plugin/standard/PluginBinaries.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(source)
    }
}

kotlin {
    jvmToolchain(17)
    jvm()
    android {
        namespace = "org.markup.poet.plugin.standard"
        compileSdk = libs.versions.android.compileSdk.get().toInt()
        minSdk = libs.versions.android.minSdk.get().toInt()

        compilations.configureEach {
            compileTaskProvider.configure {
                compilerOptions {
                    jvmTarget.set(JvmTarget.JVM_11)
                }
            }
        }
    }
    iosArm64()
    iosSimulatorArm64()
    linuxX64()
    macosArm64()
    wasmJs {
        browser()
    }

    sourceSets {
        commonMain {
            kotlin.srcDir(generatePluginBinaries.map { generatedDir })
        }
        commonTest.dependencies {
            implementation(libs.kotlin.test)
        }
    }
}
